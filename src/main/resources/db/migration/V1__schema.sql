-- Lược đồ quản lý nhà hàng. Sửa từ ERD gốc (erd_nhahang.jpg), lý do từng thay đổi ở docs/plans/2026-11-10-be-plan.md mục 12.
-- Tiền là số nguyên VND (bigint). Thời điểm là timestamptz. Không có màn hình bếp nên món chỉ có ORDERED hoặc CANCELLED.

create table roles (
    id          bigint generated by default as identity primary key,
    code        varchar(40)  not null unique,
    name        varchar(100) not null,
    description varchar(255),
    is_system   boolean not null default false,
    locked      boolean not null default false,  -- ADMIN: mọi quyền, không sửa được
    fixed       boolean not null default false   -- CUSTOMER: quyền phía khách cố định trong code
);
create table role_permissions (
    role_id    bigint not null references roles (id) on delete cascade,
    permission varchar(40) not null,
    primary key (role_id, permission)
);

create table tags (
    id   bigint generated by default as identity primary key,
    name varchar(60) not null,
    type varchar(20) not null check (type in ('TASTE', 'INGREDIENT', 'DIET', 'OCCASION', 'CUISINE'))
);

create table users (
    id            bigint generated by default as identity primary key,
    kind          varchar(10) not null check (kind in ('STAFF', 'CUSTOMER')),
    role_id       bigint references roles (id),       -- NULL: nhân viên không dùng hệ thống (bếp, phục vụ)
    full_name     varchar(100) not null,
    position      varchar(60),
    email         varchar(120) unique,
    phone         varchar(15) unique,
    password_hash varchar(100),
    status        varchar(10) not null default 'ACTIVE' check (status in ('ACTIVE', 'LOCKED')),
    work_status   varchar(10) check (work_status in ('WORKING', 'ON_LEAVE', 'QUIT')),
    hire_date     date,
    gender        varchar(10),
    points        integer not null default 0 check (points >= 0),
    created_at    timestamptz not null default now(),
    last_login_at timestamptz
);
create table user_like_tags (
    user_id bigint not null references users (id) on delete cascade,
    tag_id  bigint not null references tags (id) on delete cascade,
    primary key (user_id, tag_id)
);
create table user_allergy_tags (
    user_id bigint not null references users (id) on delete cascade,
    tag_id  bigint not null references tags (id) on delete cascade,
    primary key (user_id, tag_id)
);

create table categories (
    id         bigint generated by default as identity primary key,
    name       varchar(80) not null,
    sort_order integer not null default 0,
    is_active  boolean not null default true
);
create table ingredients (
    id        bigint generated by default as identity primary key,
    name      varchar(80) not null,
    unit      varchar(20) not null,
    stock     numeric(12, 3) not null default 0 check (stock >= 0),
    min_stock numeric(12, 3) not null default 0,
    cost      bigint not null default 0
);
create table items (
    id           bigint generated by default as identity primary key,
    category_id  bigint not null references categories (id),
    name         varchar(120) not null,
    description  varchar(500),
    price        bigint not null check (price >= 0),
    image        varchar(255),
    is_available boolean not null default true,  -- FALSE: hết món, trợ lý không được gợi ý
    spicy_level  integer not null default 0,
    prep_minutes integer not null default 10,
    deleted_at   timestamptz                      -- xóa mềm: hóa đơn cũ vẫn tham chiếu được
);
create table item_tags (
    item_id bigint not null references items (id) on delete cascade,
    tag_id  bigint not null references tags (id) on delete cascade,
    primary key (item_id, tag_id)
);
create table item_recipe (
    item_id       bigint not null references items (id) on delete cascade,
    ingredient_id bigint not null references ingredients (id),
    qty           numeric(12, 3) not null check (qty > 0),
    primary key (item_id, ingredient_id)
);

create table floors (
    id        bigint generated by default as identity primary key,
    name      varchar(60) not null,
    level     integer not null,
    is_active boolean not null default true
);
create table areas (
    id                  bigint generated by default as identity primary key,
    floor_id            bigint not null references floors (id),
    name                varchar(60) not null,
    type                varchar(10) not null check (type in ('HALL', 'OUTDOOR', 'VIP_ROOM', 'BAR')),
    service_fee_percent numeric(4, 1) not null default 0,
    min_spend           bigint not null default 0,
    is_active           boolean not null default true,
    plan_w              integer not null default 600,
    plan_h              integer not null default 400
);
create table dining_tables (
    id        bigint generated by default as identity primary key,
    area_id   bigint not null references areas (id),
    code      varchar(10) not null unique,
    seats     integer not null check (seats > 0),
    status    varchar(10) not null default 'AVAILABLE' check (status in ('AVAILABLE', 'OCCUPIED', 'RESERVED', 'CLEANING', 'DISABLED')),
    is_active boolean not null default true,
    qr_token  varchar(32) not null unique,
    shape     varchar(10) not null default 'SQUARE',
    pos_x     integer not null default 0,
    pos_y     integer not null default 0
);

create table vouchers (
    id               bigint generated by default as identity primary key,
    code             varchar(30) not null unique,
    name             varchar(120) not null,
    type             varchar(10) not null check (type in ('PERCENT', 'FIXED')),
    value            bigint not null check (value > 0),
    max_discount     bigint not null default 0,
    min_order_amount bigint not null default 0,
    start_at         timestamptz not null,
    end_at           timestamptz not null,
    usage_limit      integer not null default 0,
    used_count       integer not null default 0,
    is_active        boolean not null default true
);

create table shifts (
    id         bigint generated by default as identity primary key,
    name       varchar(40) not null,
    start_time varchar(5) not null,
    end_time   varchar(5) not null
);
create table schedules (
    id          bigint generated by default as identity primary key,
    employee_id bigint not null references users (id),
    shift_id    bigint not null references shifts (id),
    area_id     bigint references areas (id),
    work_date   date not null,
    status      varchar(10) not null default 'SCHEDULED' check (status in ('SCHEDULED', 'PRESENT', 'ABSENT')),
    unique (employee_id, shift_id, work_date)
);

create table reservations (
    id          bigint generated by default as identity primary key,
    customer_id bigint references users (id),
    guest_name  varchar(100) not null,
    guest_phone varchar(15) not null,
    time        timestamptz not null,
    guest_count integer not null check (guest_count > 0),
    area_id     bigint references areas (id),
    note        varchar(255),
    status      varchar(10) not null default 'CONFIRMED' check (status in ('CONFIRMED', 'SEATED', 'COMPLETED', 'CANCELLED', 'NO_SHOW')),
    created_at  timestamptz not null default now()
);
create table reservation_tables (
    reservation_id bigint not null references reservations (id) on delete cascade,
    table_id       bigint not null references dining_tables (id),
    primary key (reservation_id, table_id)
);

create table orders (
    id             bigint generated by default as identity primary key,
    table_id       bigint references dining_tables (id),
    reservation_id bigint references reservations (id),
    customer_id    bigint references users (id),
    opened_by      bigint references users (id),
    type           varchar(10) not null default 'DINE_IN' check (type in ('DINE_IN', 'TAKEAWAY')),
    guest_count    integer not null default 1,
    status         varchar(10) not null default 'OPEN' check (status in ('OPEN', 'COMPLETED', 'CANCELLED')),
    note           varchar(255),
    opened_at      timestamptz not null default now(),
    closed_at      timestamptz
);
create table order_items (
    id         bigint generated by default as identity primary key,
    order_id   bigint not null references orders (id),
    item_id    bigint not null references items (id),
    qty        integer not null check (qty > 0),
    unit_price bigint not null,          -- giá tại lúc gọi: đổi giá sau này không làm sai hóa đơn cũ
    note       varchar(255),
    status     varchar(10) not null default 'ORDERED' check (status in ('ORDERED', 'CANCELLED')),
    source     varchar(10) not null default 'MENU' check (source in ('MENU', 'CHATBOT', 'STAFF')),
    created_at timestamptz not null default now()
);
create table bills (
    id               bigint generated by default as identity primary key,
    order_id         bigint not null unique references orders (id),
    voucher_id       bigint references vouchers (id),
    subtotal         bigint not null,
    service_fee      bigint not null default 0,
    min_spend_top_up bigint not null default 0,
    discount         bigint not null default 0,
    points_amount    bigint not null default 0,
    tax              bigint not null default 0,
    total            bigint not null,
    points_used      integer not null default 0,
    points_earned    integer not null default 0,
    method           varchar(15) not null check (method in ('CASH', 'BANK_TRANSFER', 'CARD')),
    status           varchar(10) not null default 'PAID' check (status in ('PAID', 'VOID')),
    cashier_id       bigint references users (id),
    paid_at          timestamptz not null default now()
);
create table inventory_transactions (
    id            bigint generated by default as identity primary key,
    ingredient_id bigint not null references ingredients (id),
    type          varchar(10) not null check (type in ('IMPORT', 'EXPORT', 'ADJUST', 'CONSUME')),
    qty           numeric(12, 3) not null,
    unit_cost     bigint not null default 0,
    note          varchar(255),
    employee_id   bigint references users (id),
    created_at    timestamptz not null default now()
);
create table service_requests (
    id         bigint generated by default as identity primary key,
    table_id   bigint not null references dining_tables (id),
    order_id   bigint references orders (id),
    type       varchar(15) not null check (type in ('CALL_STAFF', 'REQUEST_BILL', 'EXTRA_WATER', 'EXTRA_UTENSIL', 'OPEN_TABLE', 'OTHER')),
    status     varchar(15) not null default 'OPEN' check (status in ('OPEN', 'ACKNOWLEDGED', 'DONE')),
    handled_by bigint references users (id),
    created_at timestamptz not null default now(),
    ack_at     timestamptz,
    done_at    timestamptz
);
create table reviews (
    id          bigint generated by default as identity primary key,
    customer_id bigint not null references users (id),
    item_id     bigint not null references items (id),
    rating      integer not null check (rating between 1 and 5),
    comment     varchar(1000),
    hidden      boolean not null default false,
    created_at  timestamptz not null default now()
);
create table chat_sessions (
    id            varchar(40) primary key,
    customer_id   bigint references users (id),
    order_id      bigint references orders (id),
    title         varchar(255),
    turns         integer not null default 0,
    feedback      integer not null default 0,
    added_to_cart boolean not null default false,
    latency_ms    integer not null default 0,
    created_at    timestamptz not null default now()
);
create table chat_messages (
    id         bigint generated by default as identity primary key,
    session_id varchar(40) not null references chat_sessions (id) on delete cascade,
    role       varchar(10) not null check (role in ('USER', 'ASSISTANT')),
    content    text not null,
    item_ids   varchar(255),               -- id món được gợi ý, cách nhau bằng dấu phẩy
    intent     varchar(20),
    latency_ms integer,
    created_at timestamptz not null default now()
);

-- Kiểm vết cho mọi bảng nghiệp vụ: tạo lúc nào, bởi ai, sửa lần cuối lúc nào, bởi ai (khớp AuditableEntity).
-- Viết một lần bằng vòng lặp để không bảng nào thiếu; bảng đã có created_at chỉ được thêm ba cột còn lại.
do $$
declare t text;
begin
    foreach t in array array['roles', 'tags', 'users', 'categories', 'ingredients', 'items', 'floors', 'areas', 'dining_tables',
                             'vouchers', 'shifts', 'schedules', 'reservations', 'orders', 'order_items', 'bills', 'inventory_transactions',
                             'service_requests', 'reviews', 'chat_sessions', 'chat_messages']
    loop
        execute format('alter table %I add column if not exists created_at timestamptz not null default now(), '
                       'add column if not exists created_by bigint references users (id), '
                       'add column if not exists updated_at timestamptz, '
                       'add column if not exists updated_by bigint references users (id)', t);
    end loop;
end $$;

create index idx_orders_status_table on orders (status, table_id);
create index idx_order_items_order on order_items (order_id);
create index idx_reservations_time on reservations (time, status);
create index idx_bills_paid_at on bills (paid_at);
create index idx_service_requests_status on service_requests (status, created_at);
create index idx_chat_messages_session on chat_messages (session_id, created_at);

-- Dữ liệu tương tác cho AI service (đọc chỉ đọc): khách–món từ đơn đã thanh toán, trọng số theo số lần gọi.
create view v_interactions as
select o.customer_id, oi.item_id, sum(oi.qty) as weight, max(o.closed_at) as ts
from order_items oi
         join orders o on o.id = oi.order_id
where o.status = 'COMPLETED' and o.customer_id is not null and oi.status = 'ORDERED'
group by o.customer_id, oi.item_id;
